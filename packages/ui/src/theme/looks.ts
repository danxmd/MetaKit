/**
 * The looks of MetaKit as data. `pnpm looks:build` writes `looks.css` from this file, and
 * `looks.test.ts` checks that the two agree and that every look is readable in light and dark.
 *
 * Components read only the tokens; no component knows which look is on. A value may refer to
 * another token of the same look with `var(--name)`; it is resolved on <html>, so it follows
 * whatever that token is there (in Workshop, the accent of the current mode).
 */

export type LookId = 'workshop' | 'drafting' | 'meadow' | 'classic';

/** In the order Settings shows them; the first is the default. */
export const LOOK_IDS: readonly LookId[] = [
  'workshop',
  'drafting',
  'meadow',
  'classic',
];
export const DEFAULT_LOOK: LookId = 'workshop';

export const isLookId = (v: unknown): v is LookId =>
  typeof v === 'string' && (LOOK_IDS as readonly string[]).includes(v);

