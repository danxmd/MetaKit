export type BaseToken = (typeof BASE_TOKENS)[number];
export type ColourToken = (typeof COLOUR_TOKENS)[number];
export type ColourTokens = Record<ColourToken, string>;

export interface Look {
  id: LookId;
  name: string;
  /** One line for Settings. */
  description: string;
  /** The families of `fonts.css` that the look uses; Classic uses none. */
  fonts: readonly string[];
  /** Three tokens whose colours stand for the look in Settings. */
  swatches: readonly [ColourToken, ColourToken, ColourToken];
  base: Record<BaseToken, string>;
  light: ColourTokens;
  dark: ColourTokens;
  /** For a look whose accent follows the mode: the tokens that change in Build mode. */
  build?: {
    light: Partial<ColourTokens>;
    dark: Partial<ColourTokens>;
  };
}

