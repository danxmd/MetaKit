/**
 * The value of a token of a look in light or dark (and Build mode, for a look whose accent
 * follows the mode), with `var(--x)` references to the look's own tokens resolved.
 */
export function lookValue(
  look: Look,
  scheme: 'light' | 'dark',
  token: BaseToken | ColourToken,
  mode: 'model' | 'build' = 'model',
): string {
  const tokens: Record<string, string> = {
    ...look.base,
    ...look[scheme],
    ...(mode === 'build' ? look.build?.[scheme] : undefined),
  };
  let value = tokens[token] ?? '';
  for (let depth = 0; depth < 8; depth++) {
    const ref = /^var\((--[a-z0-9-]+)\)$/.exec(value.trim());
    if (!ref) break;
    value = tokens[ref[1]!] ?? '';
  }
  return value;
}
